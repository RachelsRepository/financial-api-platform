#!/usr/bin/env node
/**
 * Ensure a local Compose env file with valid development ES256 JWKs.
 * Writes .env.docker (gitignored). Never commits private keys.
 */
import { generateKeyPair, exportJWK } from 'jose';
import { existsSync, writeFileSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const outPath = resolve(process.cwd(), '.env.docker');
const force = process.argv.includes('--force');

if (existsSync(outPath) && !force) {
  const existing = readFileSync(outPath, 'utf8');
  if (existing.includes('JWT_PRIVATE_JWK=') && !existing.includes('PLACEHOLDER')) {
    console.log(`.env.docker already present; reuse it (pass --force to regenerate).`);
    process.exit(0);
  }
}

const kid = 'dev-key-1';
const { privateKey, publicKey } = await generateKeyPair('ES256');
const privateJwk = await exportJWK(privateKey);
const publicJwk = await exportJWK(publicKey);
privateJwk.kid = kid;
privateJwk.alg = 'ES256';
privateJwk.use = 'sig';
publicJwk.kid = kid;
publicJwk.alg = 'ES256';
publicJwk.use = 'sig';

const contents = `# Generated by scripts/ensure-compose-env.mjs — development only. Do not commit.
JWT_ACTIVE_KID=${kid}
JWT_PRIVATE_JWK=${JSON.stringify(privateJwk)}
JWT_PUBLIC_JWKS=${JSON.stringify({ keys: [publicJwk] })}
`;

writeFileSync(outPath, contents, { mode: 0o600 });
console.log(`Wrote ${outPath}`);
